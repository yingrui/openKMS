"""Pydantic schemas for evaluation management."""
from datetime import datetime

from typing import Any, Literal

from pydantic import BaseModel, Field

#: What an item holds. Decides the editor's columns and which run types are allowed.
EvaluationKind = Literal["answer", "query", "content"]

KIND_RUN_TYPES: dict[str, tuple[str, ...]] = {
    "answer": ("search_retrieval", "qa_answer"),
    "query": ("data_query",),
    "content": ("wiki_content_coverage",),
}


class EvaluationCreate(BaseModel):
    name: str
    knowledge_base_id: str
    kind: EvaluationKind = "answer"
    wiki_space_id: str | None = None
    description: str | None = None
    #: A data-query evaluation judges a semantic model's answers (mutually exclusive with wiki in practice).
    semantic_model_id: str | None = None
    data_resource_id: str | None = None


class EvaluationUpdate(BaseModel):
    name: str | None = None
    description: str | None = None
    knowledge_base_id: str | None = None
    wiki_space_id: str | None = None
    semantic_model_id: str | None = None
    data_resource_id: str | None = None


class EvaluationResponse(BaseModel):
    id: str
    name: str
    kind: EvaluationKind = "answer"
    knowledge_base_id: str
    knowledge_base_name: str | None = None
    wiki_space_id: str | None = None
    wiki_space_name: str | None = None
    semantic_model_id: str | None = None
    data_resource_id: str | None = None
    description: str | None = None
    item_count: int = 0
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class EvaluationListResponse(BaseModel):
    items: list[EvaluationResponse]
    total: int
    limit: int
    offset: int


class EvaluationItemCreate(BaseModel):
    query: str
    #: Required for `answer`/`content` items; absent for `query` items, whose ground truth is `expected_query`.
    expected_answer: str | None = None
    topic: str | None = None
    sort_order: int = 0
    #: Data-query ground truth: every query the answer should have made.
    expected_query: list[dict[str, Any]] | None = None


class EvaluationItemUpdate(BaseModel):
    query: str | None = None
    expected_answer: str | None = None
    topic: str | None = None
    sort_order: int | None = None
    expected_query: list[dict[str, Any]] | None = None


class EvaluationItemResponse(BaseModel):
    id: str
    evaluation_id: str
    query: str
    expected_answer: str | None = None
    topic: str | None = None
    sort_order: int
    expected_query: list[dict[str, Any]] | None = None
    created_at: datetime

    model_config = {"from_attributes": True}


class EvaluationItemListResponse(BaseModel):
    items: list[EvaluationItemResponse]
    total: int


class SearchResultSnippet(BaseModel):
    """Truncated search result for evaluation response."""

    content: str
    score: float
    source_type: str


class DataQuerySource(BaseModel):
    """One query the answer cited — the thing a data-query evaluation judges.

    The arguments travel with the SQL: in metric mode the SQL is generated by the backend and its values are
    parameterised, so `group_by` / `filters` are the only record of what the answer asked for.
    """

    mode: str | None = None
    model_id: str | None = None
    metric: str | None = None
    expression: str | None = None
    group_by: list[dict[str, Any]] | None = None
    filters: list[dict[str, Any]] | None = None
    base_dataset: str | None = None
    joins: list[str] | None = None
    resource_id: str | None = None
    sql: str | None = None


class EvaluationRunResult(BaseModel):
    item_id: str
    query: str
    expected_answer: str | None = None
    search_results: list[SearchResultSnippet] = []
    generated_answer: str | None = None
    qa_sources: list[SearchResultSnippet] = []
    #: Data-query sources the answer cited (data_query evaluation only).
    data_queries: list[DataQuerySource] = []
    coverage: float | None = None
    #: What the item expected, so a result can be read without opening the item.
    expected_query: list[dict[str, Any]] | None = None
    #: Expected queries nothing covered, each with the judge's verdict for it.
    uncovered: list[dict[str, Any]] = []
    #: Queries cited that covered no expectation.
    extra_sources: int = 0
    #: The judge's structured verdict (verdict / checks / model / prompt_version).
    judge: dict[str, Any] | None = None
    pass_: bool = Field(False, alias="pass")
    score: float = 0.0
    reasoning: str = ""

    model_config = {"populate_by_name": True}


class EvaluationRunRequestBody(BaseModel):
    """Body for POST .../run."""

    evaluation_type: str = "search_retrieval"
    #: Run only these items (the ones that failed last time, a first few while tuning). Omit to run the whole set.
    item_ids: list[str] | None = None
    #: Judge this run with a different model than the knowledge base's own — for a second opinion on the same answers.
    judge_model_id: str | None = None
    #: Language for everything a person reads (check reasons, the run report). The verdicts themselves are unaffected.
    #: Omitted means the caller did not choose; the run then says so in its snapshot instead of pretending it asked.
    language: Literal["en", "zh"] | None = None


class EvaluationRunReport(BaseModel):
    """What a run says about the agent as a whole — commentary, never part of the score."""

    verdict: str = ""
    findings: list[dict[str, Any]] = []
    model: str | None = None
    prompt_version: str | None = None
    error: str | None = None


class EvaluationRunResponse(BaseModel):
    """Response after running evaluation (also matches persisted run summary + items)."""

    run_id: str
    report: EvaluationRunReport | None = None
    evaluation_type: str
    status: str
    item_count: int
    pass_count: int
    avg_score: float | None
    error_message: str | None = None
    results: list[EvaluationRunResult]


class EvaluationRunListItem(BaseModel):
    id: str
    evaluation_type: str
    status: str
    item_count: int
    pass_count: int
    avg_score: float | None
    created_at: datetime

    model_config = {"from_attributes": True}


class EvaluationRunListResponse(BaseModel):
    items: list[EvaluationRunListItem]
    total: int


class EvaluationCompareRow(BaseModel):
    evaluation_item_id: str
    query: str
    expected_answer: str | None = None
    pass_a: bool
    score_a: float
    pass_b: bool
    score_b: float
    pass_changed: bool
    score_delta: float


class EvaluationCompareResponse(BaseModel):
    run_a_id: str
    run_b_id: str
    evaluation_type_a: str
    evaluation_type_b: str
    rows: list[EvaluationCompareRow]
