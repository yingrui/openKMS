"""api — read the backend's own OpenAPI document.

The complete route table is generated by FastAPI at `/openapi.json`; the skill's reference pages carry the
routes whose *behaviour* needs explaining, not a mirror of all of them. This command is how an agent reads
the generated one without pulling a megabyte of JSON into context: `spec` prints a one-line index, and
`--path` narrows to the operations under a prefix.
"""
from __future__ import annotations

import argparse
from typing import Any

from ..client import client
from .._io import print_json


def _summarize(operations: dict[str, dict[str, Any]]) -> list[dict[str, str]]:
    out = []
    for path, item in operations.items():
        for method, op in item.items():
            if method.startswith("x-") or method == "parameters":
                continue
            out.append(
                {
                    "method": method.upper(),
                    "path": path,
                    "summary": str(op.get("summary") or ""),
                }
            )
    return out


def cmd_api_spec(ns: argparse.Namespace) -> None:
    with client() as s:
        r = s.get("/openapi.json")
    r.raise_for_status()
    spec = r.json()

    paths: dict[str, dict[str, Any]] = spec.get("paths") or {}
    if ns.path:
        prefix = ns.path.rstrip("/")
        paths = {
            p: item
            for p, item in paths.items()
            if p == prefix or p.startswith(prefix + "/") or prefix in p
        }
    if ns.method:
        wanted = ns.method.upper()
        paths = {
            p: {m: op for m, op in item.items() if m.upper() == wanted}
            for p, item in paths.items()
        }
        paths = {p: item for p, item in paths.items() if item}

    if not paths:
        print_json({"paths": {}, "hint": "no path matched; drop --path/--method for the full index"})
        return

    if ns.full:
        print_json(paths)
    else:
        print_json(_summarize(paths))


def add_subparser(sub) -> None:
    p = sub.add_parser(
        "api",
        help="read the backend's OpenAPI document (the generated route table)",
    )
    api = p.add_subparsers(dest="api_cmd", required=True)
    spec = api.add_parser("spec", help="GET /openapi.json — an index, or the operations under --path")
    spec.add_argument("--path", default=None, help="prefix to narrow to, e.g. /api/stories")
    spec.add_argument("--method", default=None, help="only this HTTP method")
    spec.add_argument(
        "--full",
        action="store_true",
        help="print the operation objects (parameters, request body, responses) instead of the index",
    )
    spec.set_defaults(fn=cmd_api_spec)
